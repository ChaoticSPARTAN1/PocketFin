"""Turn the Roboto Medium atlas (pocket/fonts, from tools/build_roboto_atlas.py) into the app's two font headers.

pocket/ui_font.h is the atlas box-scaled to 13 x 13 cells for body text; pocket/ui_font_large.h is the
18 px atlas unscaled, cropped to the rows it inks, for titles. Both keep Roboto's Apache-2.0 licence.
"""
import json
from connection_config import ROOT

NOTE = (" * Generated by tools/build_ui_font.py from pocket/fonts/roboto-medium-18.a8, which\n"
        " * tools/build_roboto_atlas.py rasterizes from Roboto Medium 2.138 (Copyright 2011 Google Inc.,\n"
        " * Apache-2.0; see pocket/fonts/NOTICE.txt and LICENSES/Apache-2.0.txt). Changed from the\n"
        " * original font: rasterized to 8-bit coverage, widened 1.125x and scaled. */\n")


def build():
    source=ROOT/"pocket/fonts"
    meta=json.loads((source/"roboto-medium-18.json").read_text())
    data=(source/"roboto-medium-18.a8").read_bytes()
    width,height=13,13
    pixels=[]
    for glyph in range(95):
        cell=data[glyph*meta["cellW"]*meta["cellH"]:(glyph+1)*meta["cellW"]*meta["cellH"]]
        for y in range(2,height):
            y0,y1=y*meta["cellH"]//height,(y+1)*meta["cellH"]//height
            for x in range(width):
                x0,x1=x*meta["cellW"]//width,(x+1)*meta["cellW"]//width
                values=[cell[sy*meta["cellW"]+sx] for sy in range(y0,y1) for sx in range(x0,x1)]
                pixels.append(sum(values)//len(values))
    advances=[max(2,round(advance*4/9)) for advance in meta["adv"]]
    header=("/* SPDX-License-Identifier: Apache-2.0\n"
            " * Roboto Medium raster atlas, scaled to 13 x 13 cells for body text.\n"+NOTE+
            "#ifndef POCKET_UI_FONT_H\n#define POCKET_UI_FONT_H\n"
            "static const unsigned char pj_font_advance[95]={"+",".join(map(str,advances))+"};\n"
            "static const unsigned char pj_font_alpha[13585]={\n")
    for start in range(0,len(pixels),52):header+=",".join(map(str,pixels[start:start+52]))+",\n"
    header+="};\n#endif\n"
    (ROOT/"pocket/ui_font.h").write_text(header)
    # Titles use the 18 px atlas unscaled, cropped to the rows it inks.
    cell_size=meta["cellW"]*meta["cellH"]
    rows=[y for y in range(meta["cellH"]) if any(data[g*cell_size+y*meta["cellW"]+x]
          for g in range(95) for x in range(meta["cellW"]))]
    top,bottom=rows[0],rows[-1]+1
    large=[]
    for glyph in range(95):
        for y in range(top,bottom):
            start=glyph*cell_size+y*meta["cellW"]
            large.extend(data[start:start+meta["cellW"]])
    body=("/* SPDX-License-Identifier: Apache-2.0\n"
          " * Roboto Medium 18 px raster atlas for titles.\n"+NOTE+
          "#ifndef POCKET_UI_FONT_LARGE_H\n#define POCKET_UI_FONT_LARGE_H\n"
          f"#define PJ_FONT_LARGE_W {meta['cellW']}\n#define PJ_FONT_LARGE_H {bottom-top}\n"
          f"#define PJ_FONT_LARGE_OX {meta['ox']}\n"
          "static const unsigned char pj_font_large_advance[95]={"+",".join(map(str,meta["adv"]))+"};\n"
          f"static const unsigned char pj_font_large[{len(large)}]={{\n")
    for start in range(0,len(large),64):body+=",".join(map(str,large[start:start+64]))+",\n"
    body+="};\n#endif\n"
    (ROOT/"pocket/ui_font_large.h").write_text(body)


if __name__=="__main__":build()
